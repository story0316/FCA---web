export function getAllJobItems() {
  return HR_JOB_TREE.flatMap(cat =>
    cat.children.map(child => ({ ...child, category: cat.name_ko, categoryId: cat.id, categoryColor: cat.color }))
  );
}

export function getJobItemById(id) {
  for (const cat of HR_JOB_TREE) {
    const item = cat.children.find(c => c.id === id);
    if (item) return { ...item, category: cat.name_ko, categoryId: cat.id, categoryColor: cat.color };
  }
  return null;
}
